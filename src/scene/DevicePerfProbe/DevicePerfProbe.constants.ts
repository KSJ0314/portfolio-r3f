/**
 * 성능을 재려고 찍어 보는 알갱이 수.
 *
 * 크레파스가 하는 일이 굵기 안쪽에 작은 사각형을 흩뿌리는 것이라, 같은 일을 정해진 양만큼
 * 시켜 봐야 그 기기가 그것을 얼마나 빨리 하는지 알 수 있다.
 * 적게 찍으면 걸린 시간이 몇 ms에 그쳐, 그 순간의 잡음에 묻혀 기기 차이가 드러나지 않는다.
 * 잡음보다 충분히 긴 시간이 나오도록 넉넉히 찍는다.
 */
export const BENCH_GRAINS = 300000

/** 재는 캔버스 한 변(px). 실제로 굽는 텍스처와 비슷한 크기라야 메모리 접근 양상이 비슷하다. */
export const BENCH_CANVAS = 1024

/**
 * 버겁다고 보는 시간(ms). 이보다 오래 걸리면 `strained`다.
 *
 * 재는 것이 화면 갱신이 아니라 **정해진 양의 그리기**라 주사율에 묶이지 않는다.
 * 그래서 60Hz든 144Hz든 같은 뜻이고, 값 자체가 곧 그 기기의 그리기 속도다.
 */
export const STRAINED_MS = 150
